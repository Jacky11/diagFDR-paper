#!/usr/bin/env python3
"""Audit of FDR reporting in DIA proteomics articles: extraction, verification,
summary and tables.

The audit has one source of truth, `scoring.csv`: one row per article,
with the score of every item and, beside each score, the sentence of the article
that supports it, quoted verbatim. This script does four things with it.

    extract    PDFs -> text -> candidate sentences for each item.
               Locates sentences; assigns no score.
    check      Five verification checks on the scoring sheet (see CHECKS).
    summarise  Prints every number quoted in the paper.
    build      Writes the tables of the paper (LaTeX), the list of numbers and
               the workbook distributed as Supplementary Data S1.

Usage
-----
    python audit_pipeline.py extract   --pdf-dir pdfs --out-dir work
    python audit_pipeline.py check     --sheet scoring.csv --txt-dir work/txt
    python audit_pipeline.py summarise --sheet scoring.csv
    python audit_pipeline.py build     --sheet scoring.csv --out-dir out

`extract` needs `pdftotext` (poppler-utils). `build` needs `openpyxl` for the
workbook; the LaTeX tables and the list of numbers need nothing beyond the
standard library. `check` without --txt-dir runs the checks that do not need the
article texts.

The PDFs are not distributed. Each row of the sheet names its file
(`pdf_file`) and its DOI, so the texts can be regenerated by anyone with access
to the articles.
"""

