# --------------------------------------------------------------------------
# Text handling
# --------------------------------------------------------------------------

LIGATURES = {"\ufb00": "ff", "\ufb01": "fi", "\ufb02": "fl", "\ufb03": "ffi",
             "\ufb04": "ffl"}


def squash(text):
    """Reduce a text to lower-case letters and digits.

    Used to compare a quote with its source. Ligatures are expanded first;
    whitespace, hyphenation at line ends, punctuation and typographic variants
    of the same character then disappear, so a quote matches when the same
    words occur in the same order with nothing in between."""
    text = unicodedata.normalize("NFKC", text)
    for bad, good in LIGATURES.items():
        text = text.replace(bad, good)
    return re.sub(r"[^a-z0-9]", "", text.lower())


def clean(text):
    """Readable single-line version of a text: ligatures expanded, words
    hyphenated across a line break joined, whitespace collapsed."""
    text = unicodedata.normalize("NFKC", text)
    for bad, good in LIGATURES.items():
        text = text.replace(bad, good)
    text = re.sub(r"(\w)-\n(\w)", r"\1\2", text)
    return re.sub(r"\s+", " ", text).strip()


def quote_parts(quote):
    """A quote may join passages with ' [...] '; each passage is checked."""
    return [p for p in re.split(r"\s*\[\.\.\.\]\s*", quote) if p.strip()]


def pdf_to_text(pdf_path, layout):
    args = ["pdftotext", "-enc", "UTF-8"] + (["-layout"] if layout else [])
    out = subprocess.run(args + [pdf_path, "-"], capture_output=True, timeout=300)
    if out.returncode != 0:
        raise RuntimeError("pdftotext failed on %s" % pdf_path)
    return out.stdout.decode("utf-8", "replace")


def split_sentences(text):
    text = re.sub(r"\b(e\.g|i\.e|cf|vs|approx|ca|Fig|Figs|Ref|et al)\.",
                  lambda m: m.group(0)[:-1] + "\u2024", text)
    parts = re.split(r"(?<=[.;!?])\s+(?=[A-Z0-9(])", text)
    return [p.replace("\u2024", ".").strip() for p in parts if p.strip()]


# Patterns that locate candidate sentences. They are deliberately broad: a
# sentence retrieved in excess costs a reader a few seconds, a sentence missed
# could become a wrong "No".
PATTERNS = {
    "fdr": r"false[- ]discovery|\bFDR\b|q[- ]?values?|\bPEP\b|posterior error",
    "decoy": r"decoy|target[- ]decoy|reversed? (sequence|database)|shuffl",
    "entrapment": r"entrap|known[- ]composition|wrong[- ]organism|empirical FDR",
    "mbr": r"match[- ]between[- ]runs?|\bMBR\b|reanaly[sz]e",
    "scope": r"run[- ]specific|run[- ]wise|global|experiment[- ]wide|per (run|file)",
    "field": r"Q\.Value|Qvalue|PG\.Q|Lib\.Q|Global\.Q|EG\.|--?qvalue",
    "count": r"\d[\d,]*\s+(unique |quantified |identified )?(protein groups?|proteins|peptides|precursors|PSMs)",
    "software": r"DIA-?NN|Spectronaut|MaxQuant|FragPipe|MSFragger|Proteome Discoverer|PEAKS|Skyline|EncyclopeDIA|Mascot|version|default",
}


def cmd_extract(args):
    txt_dir = os.path.join(args.out_dir, "txt")
    os.makedirs(txt_dir, exist_ok=True)
    rows = []
    pdfs = sorted(f for f in os.listdir(args.pdf_dir) if f.lower().endswith(".pdf"))
    for pdf in pdfs:
        stem = pdf[:-4]
        path = os.path.join(args.pdf_dir, pdf)
        # Two renderings: reading order (sentences stay whole in two-column
        # articles) and physical layout (tables and captions stay whole).
        reading = pdf_to_text(path, layout=False)
        layout = pdf_to_text(path, layout=True)
        with open(os.path.join(txt_dir, stem + ".txt"), "w", encoding="utf-8") as f:
            f.write(reading)
        with open(os.path.join(txt_dir, stem + ".layout.txt"), "w", encoding="utf-8") as f:
            f.write(layout)
        for sentence in split_sentences(clean(reading)):
            if len(sentence) > 1200:
                continue
            for item, pattern in PATTERNS.items():
                if re.search(pattern, sentence, flags=re.I):
                    rows.append({"pdf_file": pdf, "item": item, "sentence": sentence})
        print("  %s" % pdf)
    out = os.path.join(args.out_dir, "candidate_sentences.csv")
    with open(out, "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=["pdf_file", "item", "sentence"])
        w.writeheader()
        w.writerows(rows)
    print("%d articles, %d candidate sentences -> %s" % (len(pdfs), len(rows), out))


