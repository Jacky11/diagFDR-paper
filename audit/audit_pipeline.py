def tex_table_reporting(rows):
    S = summary(rows)
    n, y, p = S["n_included"], S["yes"], S["partial"]

    def row(label, k):
        return "%s & %d & %s \\\\" % (label, k, pct(k, n).replace("%", ""))

    L = ["\\begin{tabular}{p{10.4cm}rr}", "\\toprule",
         "\\textbf{Reporting item} & \\textbf{$n$/%d} & \\textbf{\\%%} \\\\" % n,
         "\\midrule",
         "\\multicolumn{3}{l}{\\textit{The ten criteria}}\\\\",
         row("1. Controlled unit named (PSM, precursor, peptide, protein group)", y["unit"]),
         row("2. Identification count and threshold both reported, anywhere", y["count_rule1"]),
         row("3. \\quad \\dots\\ reported together", y["count_joint"]),
         row("4. \\quad \\dots\\ and the count is of the controlled unit", y["count_unit"]),
         row("5. Scope stated (run-wise or global)", y["scope"]),
         row("6. Match-between-runs setting stated", y["mbr"]),
         row("7. Thresholded confidence column named (e.g.\\ \\texttt{Global.Q.Value})", y["qfield"]),
         row("8. Accepted decoy count $D$ reported", y["decoy_count"]),
         row("9. Target/decoy label-propagation rule stated", y["label_rule"]),
         row("10. External validation (entrapment or known composition) performed", y["external"]),
         "\\midrule",
         "\\multicolumn{3}{l}{\\textit{Descriptors}}\\\\",
         row("Identification count reported, with or without a threshold", y["count_any"]),
         row("Numeric identification-level threshold stated", y["id_fdr"]),
         row("No identification-level threshold stated at all", S["no_id_fdr"]),
         row("\\quad of which a differential-abundance threshold is stated", S["no_id_fdr_but_da"]),
         row("Identification threshold stated, but none at protein level", S["no_protein_threshold"]),
         row("Search software version given", y["version"]),
         row("Search described as default settings", y["defaults"]),
         row("Decoy generation strategy named", y["decoy_strategy"]),
         row("Posterior error probability used or reported", y["pep"]),
         "\\bottomrule", "\\end{tabular}"]
    return "\n".join(L) + "\n"


def tex_table_corpus(rows):
    S = summary(rows)
    n = S["n_included"]
    journals = S["journals"].most_common()
    multi = [(j, c) for j, c in journals if c > 1]
    single = sum(1 for j, c in journals if c == 1)
    left = [("\\textbf{Journal}", "\\textbf{$n$}")]
    left += [(j.replace("&", "\\&"), str(c)) for j, c in multi]
    left += [("%d further journals, one article each" % single, str(single))]
    right = [("\\textbf{Article type}", "\\textbf{$n$}")]
    for t in ["Applied study", "Method or tool", "Benchmark"]:
        right.append((t, str(S["types"].get(t, 0))))
    right.append(("", ""))
    right.append(("\\textbf{Year}", ""))
    for yr in sorted(S["years"]):
        right.append((str(yr), str(S["years"][yr])))
    right.append(("", ""))
    right.append(("\\textbf{Acquisition}", ""))
    right.append(("DIA only", str(n - S["other_arm"])))
    right.append(("DIA with a DDA, TMT or targeted arm", str(S["other_arm"])))
    soft = S["software"].most_common()
    main = [(s, c) for s, c in soft if c >= 2]
    rest = [s for s, c in soft if c == 1]
    left2 = [("\\textbf{Software (mentions)}", "")]
    left2 += [(s, str(c)) for s, c in main]
    if rest:
        left2.append(("%d others, one mention each" % len(rest), str(len(rest))))
    right2 = [("\\textbf{Totals}", ""),
              ("Journals", str(len(S["journals"]))),
              ("Distinct software combinations", str(S["software_combinations"])),
              ("Articles using more than one software", str(S["software_multi"]))]

    def block(a, b):
        out = []
        for i in range(max(len(a), len(b))):
            l = a[i] if i < len(a) else ("", "")
            r = b[i] if i < len(b) else ("", "")
            out.append("%s & %s & %s & %s \\\\" % (l[0], l[1], r[0], r[1]))
        return out

    L = ["\\begin{tabular}{lr@{\\hspace{2.2em}}lr}", "\\toprule"]
    b1 = block(left, right)
    L += [b1[0], "\\midrule"] + b1[1:] + ["\\midrule"]
    L += block(left2, right2)
    L += ["\\bottomrule", "\\end{tabular}"]
    return "\n".join(L) + "\n"


