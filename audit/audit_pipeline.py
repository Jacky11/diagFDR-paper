def read_sheet(path):
    with open(path, newline="", encoding="utf-8-sig") as f:
        rows = list(csv.DictReader(f))
    for r in rows:
        r["count_rule1"] = ""
        if r["included"] == "Yes":
            both = r["count_any"] == "Yes" and r["id_fdr"] == "Yes"
            r["count_rule1"] = "Yes" if both else "No"
            r["criteria_met"] = sum(r[k] == "Yes" for k, _ in CRITERIA)
    return rows


def included(rows):
    return [r for r in rows if r["included"] == "Yes"]


# --------------------------------------------------------------------------
# Verification
# --------------------------------------------------------------------------

CHECKS = """
  1. the DOI recorded for an article occurs in the text of that article;
  2. every evidence quote occurs in the text of its article;
  3. every score other than No carries a quote and every No carries none;
  4. the scores are logically consistent (a count reported with its threshold
     implies a count and a threshold; a count of the controlled unit implies a
     count reported with its threshold; a named unit or a named column implies
     an identification-level statement; an article marked as not scored has a reason
     and no score);
  5. no DOI occurs twice.
"""


def load_text(txt_dir, pdf_file):
    stem = pdf_file[:-4] if pdf_file.lower().endswith(".pdf") else pdf_file
    out = ""
    for name in (stem + ".txt", stem + ".layout.txt"):
        p = os.path.join(txt_dir, name)
        if os.path.exists(p):
            with open(p, encoding="utf-8", errors="replace") as f:
                out += " " + squash(f.read())
    return out


def cmd_check(args):
    rows = read_sheet(args.sheet)
    problems = []
    skipped = []

    # 5. duplicate DOIs
    dois = Counter(r["doi"].strip().lower() for r in rows)
    for doi, n in dois.items():
        if n > 1:
            problems.append("check 5: DOI %s occurs %d times" % (doi, n))

    # 3 and 4. quotes present where needed; logic
    for r in rows:
        tag = "%s (%s %s)" % (r["id"], r["first_author"], r["year"])
        if r["included"] != "Yes":
            if not r["exclusion_criterion"] or not r["exclusion_reason"]:
                problems.append("check 4: %s excluded without a reason" % tag)
            if any(r[k] for k in SCORED):
                problems.append("check 4: %s excluded but carries scores" % tag)
            continue
        for k in SCORED:
            score, quote = r[k], r["q_" + k].strip()
            allowed = {"Yes", "Partial", "No"} if k in GRADED else {"Yes", "No"}
            if score not in allowed:
                problems.append("check 3: %s %s has score %r" % (tag, k, score))
            if score != "No" and not quote:
                problems.append("check 3: %s %s is %s without a quote" % (tag, k, score))
            if score == "No" and quote:
                problems.append("check 3: %s %s is No with a quote" % (tag, k))
        if r["count_joint"] == "Yes" and r["count_rule1"] != "Yes":
            problems.append("check 4: %s count_joint without count_any and id_fdr" % tag)
        if r["count_unit"] == "Yes" and r["count_joint"] != "Yes":
            problems.append("check 4: %s count_unit without count_joint" % tag)
        if r["unit"] != "No" and r["id_fdr"] == "No":
            problems.append("check 4: %s unit named without identification statement" % tag)
        if r["qfield"] == "Yes" and r["id_fdr"] == "No":
            problems.append("check 4: %s column named without identification statement" % tag)
        if r["version"] == "Yes" and not r["version_text"].strip():
            problems.append("check 4: %s version Yes without version text" % tag)

    # 1 and 2. need the texts
    n_quotes = 0
    if args.txt_dir:
        for r in rows:
            tag = "%s (%s %s)" % (r["id"], r["first_author"], r["year"])
            text = load_text(args.txt_dir, r["pdf_file"])
            if not text:
                problems.append("checks 1-2: no text found for %s (%s)" % (tag, r["pdf_file"]))
                continue
            if squash(r["doi"]) not in text:
                problems.append("check 1: DOI %s not found in %s" % (r["doi"], tag))
            fields = ["exclusion_quote"] if r["included"] != "Yes" else ["q_" + k for k in SCORED]
            for fld in fields:
                for part in quote_parts(r[fld]):
                    n_quotes += 1
                    if len(squash(part)) >= 6 and squash(part) not in text:
                        problems.append("check 2: %s %s: quote not found: %s" % (tag, fld, part[:80]))
    else:
        skipped = ["1 (DOI in text)", "2 (quotes in text)"]

    print("Verification of %s: %d articles" % (args.sheet, len(rows)))
    print(CHECKS)
    if skipped:
        print("SKIPPED, no --txt-dir given: checks %s" % ", ".join(skipped))
    else:
        print("%d quoted passages compared with the article texts" % n_quotes)
    if problems:
        print("\n%d PROBLEM(S):" % len(problems))
        for p in problems:
            print("  " + p)
        sys.exit(1)
    print("\nAll checks that were run passed.")


