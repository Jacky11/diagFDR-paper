def cmd_build(args):
    rows = read_sheet(args.sheet)
    os.makedirs(args.out_dir, exist_ok=True)
    out = lambda name: os.path.join(args.out_dir, name)
    with open(out("tableS3_audit.tex"), "w", encoding="utf-8") as f:
        f.write(tex_table_reporting(rows))
    with open(out("tableS5_corpus.tex"), "w", encoding="utf-8") as f:
        f.write(tex_table_corpus(rows))
    with open(out("audit_numbers.txt"), "w", encoding="utf-8") as f:
        f.write(numbers_text(rows))
    print("wrote tableS3_audit.tex, tableS5_corpus.tex, audit_numbers.txt")
    try:
        import openpyxl
        from openpyxl.styles import Alignment, Font, PatternFill
    except ImportError:
        print("openpyxl not installed: workbook not written")
        return

    inc = included(rows)
    exc = [r for r in rows if r["included"] != "Yes"]
    S = summary(rows)
    n = S["n_included"]
    wb = openpyxl.Workbook()
    bold = Font(bold=True)
    wrap = Alignment(wrap_text=True, vertical="top")
    fills = {"Yes": PatternFill("solid", fgColor="C6E0B4"),
             "Partial": PatternFill("solid", fgColor="FFE699"),
             "No": PatternFill("solid", fgColor="F2F2F2")}

    def sheet(title, header, data, widths):
        ws = wb.create_sheet(title)
        ws.append(header)
        for c in ws[1]:
            c.font = bold
            c.alignment = wrap
        for line in data:
            ws.append(line)
        for i, w in enumerate(widths, 1):
            ws.column_dimensions[openpyxl.utils.get_column_letter(i)].width = w
        for row in ws.iter_rows(min_row=2):
            for c in row:
                c.alignment = wrap
                if c.value in fills:
                    c.fill = fills[c.value]
        ws.freeze_panes = "A2"
        return ws

    ws = wb.active
    ws.title = "README"
    for text, kind in README_TEXT:
        ws.append([text % {"n": n} if "%(n)d" in text else text])
        c = ws.cell(row=ws.max_row, column=1)
        c.alignment = wrap
        if kind in ("title", "head"):
            c.font = Font(bold=True, size=13 if kind == "title" else 11)
    ws.column_dimensions["A"].width = 120

    crit_keys = [k for k, _ in CRITERIA]
    desc_keys = ["id_fdr", "count_any", "da_fdr", "contradiction", "pep",
                 "decoy_strategy", "defaults", "version"]
    header = (["ID", "First author", "Year", "Journal", "DOI", "Title", "Article type",
               "Acquisition", "Software", "Version"]
              + ["%d. %s" % (i, lab) for i, (_, lab) in enumerate(CRITERIA, 1)]
              + ["Criteria met (of 10)"] + [LABELS[k] for k in desc_keys]
              + ["Threshold, PSM/peptide/precursor", "Threshold, protein", "Remark"])
    data = []
    for r in inc:
        data.append([r["id"], r["first_author"], int(r["year"]), r["journal"], r["doi"],
                     r["title"], r["article_type"], r["acquisition"], r["software"],
                     r["version_text"]] + [r[k] for k in crit_keys] + [r["criteria_met"]]
                    + [r[k] for k in desc_keys]
                    + [r["pp_threshold"], r["protein_threshold"], r["remark"]])
    sheet("Scores", header, data, [6, 16, 6, 26, 28, 50, 14, 22, 30, 22] + [12] * 10 + [9] + [12] * 8 + [26, 22, 50])

    ev_keys = ["id_fdr", "unit", "count_any", "count_joint", "count_unit", "scope", "mbr",
               "qfield", "decoy_count", "label_rule", "external", "da_fdr", "pep",
               "decoy_strategy", "defaults", "version"]
    header = ["ID", "First author", "Year", "DOI"]
    for k in ev_keys:
        header += [LABELS[k] + ": score", LABELS[k] + ": evidence"]
    data = []
    for r in inc:
        line = [r["id"], r["first_author"], int(r["year"]), r["doi"]]
        for k in ev_keys:
            line += [r[k], r["q_" + k]]
        data.append(line)
    sheet("Evidence", header, data, [6, 16, 6, 28] + [9, 60] * len(ev_keys))

    header = ["ID", "First author", "Year", "Journal", "DOI", "Title", "Article type",
              "Acquisition", "Software", "Criterion", "Criterion (text)", "Reason", "Supporting passage"]
    data = [[r["id"], r["first_author"], int(r["year"]), r["journal"], r["doi"], r["title"],
             r["article_type"], r["acquisition"], r["software"], r["exclusion_criterion"],
             EXCLUSION[r["exclusion_criterion"]], r["exclusion_reason"], r["exclusion_quote"]]
            for r in exc]
    if exc:
        sheet("Not scored", header, data, [6, 16, 6, 26, 28, 50, 14, 22, 24, 9, 40, 50, 60])

    y, p = S["yes"], S["partial"]
    data = [["Articles (n)", n, "", "", ""],
            ["", "", "", "", ""],
            ["The ten criteria", "Yes", "Partial", "No", "% Yes"]]
    for i, (k, lab) in enumerate(CRITERIA, 1):
        pa = p.get(k, 0) if k in GRADED else 0
        data.append(["%d. %s" % (i, lab), y[k], pa, n - y[k] - pa, pct(y[k], n)])
    data += [["", "", "", "", ""], ["Descriptors", "Yes", "Partial", "No", "% Yes"]]
    for k in desc_keys:
        pa = p.get(k, 0) if k in GRADED else 0
        data.append([LABELS[k], y[k], pa, n - y[k] - pa, pct(y[k], n)])
    data += [["Identification threshold stated, none at protein level", S["no_protein_threshold"], "", "", pct(S["no_protein_threshold"], n)],
             ["No identification threshold, differential-abundance threshold stated", S["no_id_fdr_but_da"], "", "", pct(S["no_id_fdr_but_da"], n)],
             ["", "", "", "", ""],
             ["Criteria met per article: median", S["met_median"], "", "", ""],
             ["Articles meeting none of the ten criteria", S["met_zero"], "", "", ""],
             ["Largest number of criteria met by one article", S["met_max"], "", "", ""]]
    ws = sheet("Summary", ["Item", "", "", "", ""], data, [66, 10, 10, 10, 10])
    for row in ws.iter_rows():
        if row[0].value in ("The ten criteria", "Descriptors"):
            for c in row:
                c.font = bold

    header = ["Item", "Role", "What is scored", "Yes when", "Partial when", "Note"]
    data = [[LABELS.get(k, "Identification count and threshold both reported"), role, a, b, c, d]
            for k, role, a, b, c, d in CODEBOOK]
    sheet("Codebook", header, data, [36, 13, 50, 50, 44, 44])

    wb.save(out("Data_S1_audit.xlsx"))
    print("wrote Data_S1_audit.xlsx")


