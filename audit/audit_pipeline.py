def pct(n, d):
    return "%d%%" % int(n * 100.0 / d + 0.5) if d else "-"


def summary(rows):
    inc = included(rows)
    exc = [r for r in rows if r["included"] != "Yes"]
    n = len(inc)
    S = {"n_screened": len(rows), "n_included": n, "n_excluded": len(exc)}
    S["exclusions"] = Counter(r["exclusion_criterion"] for r in exc)
    S["yes"] = {k: sum(r[k] == "Yes" for r in inc) for k in SCORED + ["count_rule1"]}
    S["partial"] = {k: sum(r[k] == "Partial" for r in inc) for k in SCORED}
    met = sorted(r["criteria_met"] for r in inc)
    S["met_median"] = statistics.median(met)
    S["met_zero"] = met.count(0)
    S["met_max"] = max(met)
    S["met_best"] = [r for r in inc if r["criteria_met"] == max(met)]
    S["no_id_fdr"] = sum(r["id_fdr"] == "No" for r in inc)
    S["no_id_fdr_but_da"] = sum(r["id_fdr"] == "No" and r["da_fdr"] == "Yes" for r in inc)
    S["id_and_da"] = sum(r["id_fdr"] != "No" and r["da_fdr"] == "Yes" for r in inc)
    S["no_protein_threshold"] = sum(
        r["id_fdr"] == "Yes" and not r["protein_threshold"].strip() for r in inc)
    S["types"] = Counter(r["article_type"] for r in inc)
    S["years"] = Counter(r["year"] for r in inc)
    S["journals"] = Counter(r["journal"] for r in inc)
    S["other_arm"] = sum(bool(re.search(r"DDA|TMT|PRM", r["acquisition"])) for r in inc)
    soft = Counter()
    combos = Counter()
    multi = 0
    for r in inc:
        found = tuple(sorted(name for name, pat in SOFTWARE
                             if re.search(pat, r["software"], flags=re.I)))
        soft.update(found)
        combos[found] += 1
        multi += len(found) > 1
    S["software"] = soft
    S["software_combinations"] = len(combos)
    S["software_multi"] = multi
    S["external_by_type"] = Counter(r["article_type"] for r in inc if r["external"] == "Yes")
    return S


def numbers_text(rows):
    S = summary(rows)
    n = S["n_included"]
    y, p = S["yes"], S["partial"]
    L = []
    add = L.append
    add("Numbers of the audit, as quoted in the paper")
    add("=" * 44)
    if S["n_excluded"]:
        add("Articles in the sheet                      %d" % S["n_screened"])
        add("Articles not scored                        %d" % S["n_excluded"])
        for c in "abcd":
            add("    (%s) %-52s %d" % (c, EXCLUSION[c], S["exclusions"].get(c, 0)))
    add("Articles (n)                               %d" % n)
    add("")
    add("The ten criteria                               Yes        Partial")
    for k, label in CRITERIA:
        add("  %-46s %2d (%s)   %s" % (label, y[k], pct(y[k], n),
                                         p.get(k, 0) if k in GRADED else "-"))
    add("")
    add("Identification count reported anywhere         %2d (%s)" % (y["count_any"], pct(y["count_any"], n)))
    add("Controlled unit, Yes or Partial                %2d (%s)" % (y["unit"] + p["unit"], pct(y["unit"] + p["unit"], n)))
    add("Criteria met per article: median %g, none met by %d, maximum %d (%s)" % (
        S["met_median"], S["met_zero"], S["met_max"],
        "; ".join("%s %s" % (r["first_author"], r["year"]) for r in S["met_best"])))
    add("")
    add("Descriptors")
    add("  Identification threshold stated (numeric)    %2d (%s); mentioned without a number %d; not stated %d (%s)" % (
        y["id_fdr"], pct(y["id_fdr"], n), p["id_fdr"], S["no_id_fdr"], pct(S["no_id_fdr"], n)))
    add("    of the latter, a differential-abundance threshold is stated   %d" % S["no_id_fdr_but_da"])
    add("  Identification and differential-abundance thresholds both stated  %d (%s)" % (S["id_and_da"], pct(S["id_and_da"], n)))
    add("  Identification threshold stated, none at protein level        %d (%s)" % (S["no_protein_threshold"], pct(S["no_protein_threshold"], n)))
    for k in ["version", "defaults", "decoy_strategy", "pep", "contradiction"]:
        add("  %-46s %2d (%s)" % (LABELS[k], y[k], pct(y[k], n)))
    add("  Software version not given                     %2d (%s)" % (n - y["version"], pct(n - y["version"], n)))
    add("")
    add("Composition")
    add("  Journals                                     %d" % len(S["journals"]))
    for t, c in S["types"].most_common():
        add("  %-44s %d" % (t, c))
    for yr in sorted(S["years"]):
        add("  Published %s                               %d" % (yr, S["years"][yr]))
    add("  DIA only / with a DDA, TMT or targeted arm   %d / %d" % (n - S["other_arm"], S["other_arm"]))
    add("  Distinct software combinations               %d" % S["software_combinations"])
    add("  Articles using more than one software        %d" % S["software_multi"])
    add("  External validation by article type          %s" % dict(S["external_by_type"]))
    return "\n".join(L) + "\n"


def cmd_summarise(args):
    sys.stdout.write(numbers_text(read_sheet(args.sheet)))


