## Parse UniProt accessions from a FASTA. Handles ">sp|ACC|NAME ..." and
## bare ">ACC ..." headers. Used for entrapment attribution: DIA-NN's
## Protein.Group holds bare accessions with no species tag, so matching a
## string such as "ARATH" finds nothing.
entrap_accessions <- function(path) {
  ln <- readLines(path, warn = FALSE)
  h  <- ln[startsWith(ln, ">")]
  a  <- sub("^>(?:sp|tr)\\|([^|]+)\\|.*$", "\\1", h)
  a  <- ifelse(a == h, sub("^>([^ \t]+).*$", "\\1", h), a)
  unique(a)
}

## Read a FASTA into ids + sequences (base R).
read_fasta <- function(path) {
  ln  <- readLines(path, warn = FALSE)
  hdr <- grepl("^>", ln)
  ids <- sub("^>", "", ln[hdr])
  grp <- cumsum(hdr)
  seqs <- tapply(ln[!hdr], grp[!hdr], function(x) paste0(x, collapse = ""))
  list(ids = ids, seqs = toupper(unname(seqs[order(as.integer(names(seqs)))])))
}

## Trypsin/P digest. p_rule = TRUE suppresses cleavage before proline.
digest <- function(seq, missed = 1, min_len = 6, max_len = 30, p_rule = FALSE) {
  ch <- strsplit(seq, "")[[1]]
  cut_at <- which(ch %in% c("K", "R"))
  if (p_rule && length(cut_at)) {
    nxt <- ch[pmin(cut_at + 1, length(ch))]
    cut_at <- cut_at[nxt != "P"]
  }
  bounds <- unique(c(0, cut_at, length(ch)))
  out <- character(0)
  for (m in 0:missed) {
    i <- seq_len(length(bounds) - 1 - m)
    if (!length(i)) next
    out <- c(out, substring(seq, bounds[i] + 1, bounds[i + 1 + m]))
  }
  n <- nchar(out)
  unique(out[n >= min_len & n <= max_len])
}
