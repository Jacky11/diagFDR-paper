wilson <- function(k, n, conf = 0.95) {
  if (n == 0) return(c(est = NA, lo = NA, hi = NA))
  z <- qnorm(1 - (1 - conf) / 2)
  p <- k / n
  den <- 1 + z^2 / n
  ctr <- (p + z^2 / (2 * n)) / den
  hw  <- z * sqrt(p * (1 - p) / n + z^2 / (4 * n^2)) / den
  c(est = p, lo = ctr - hw, hi = ctr + hw)
}

## Target-decoy competition q-values from scores and labels.
tdc_qvalues <- function(score, is_decoy, offset = 0) {
  o  <- order(score, decreasing = TRUE)
  L  <- as.integer(is_decoy[o] == 0L)          # 1 = target
  Tc <- cumsum(L == 1L); Dc <- cumsum(L == 0L)
  fdr <- (Dc + offset) / pmax(Tc, 1)
  q <- rev(cummin(rev(fdr)))
  out <- numeric(length(score)); out[o] <- q
  out
}

