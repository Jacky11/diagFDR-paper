## ---------------------------------------------------------------------
##  NUMBER REGISTRY
##
##  Each script registers the numbers it produces under a name, with a
##  note saying where the number is used. write_numbers_tex() writes the
##  registry to out/numbers.tex as LaTeX macros.
## ---------------------------------------------------------------------

.NUMBERS <- new.env(parent = emptyenv())

reg <- function(name, value, fmt = NULL, note = "") {
  stopifnot(grepl("^[A-Za-z]+$", name))   # LaTeX macro names: letters only
  assign(name, list(value = value, fmt = fmt, note = note), envir = .NUMBERS)
  invisible(value)
}

reg_get <- function(name) get(name, envir = .NUMBERS)$value

fmt_num <- function(x, fmt = NULL) {
  if (is.null(fmt)) {
    if (is.character(x)) return(x)
    if (is.numeric(x) && x == round(x) && abs(x) >= 1000)
      return(formatC(x, format = "d", big.mark = "{,}"))
    if (is.numeric(x) && x == round(x)) return(formatC(x, format = "d"))
    return(formatC(x, format = "g", digits = 4))
  }
  if (fmt == "int")   return(formatC(x, format = "d", big.mark = "{,}"))
  if (fmt == "pct2")  return(paste0(formatC(100 * x, format = "f", digits = 2)))
  if (fmt == "pct1")  return(paste0(formatC(100 * x, format = "f", digits = 1)))
  if (fmt == "pct0")  return(paste0(formatC(100 * x, format = "f", digits = 0)))
  if (fmt == "d3")    return(formatC(x, format = "f", digits = 3))
  if (fmt == "d4")    return(formatC(x, format = "f", digits = 4))
  if (fmt == "d5")    return(formatC(x, format = "f", digits = 5))
  formatC(x, format = "g", digits = 4)
}

write_numbers_tex <- function(path = NUMFILE) {
  nms <- sort(ls(envir = .NUMBERS))
  if (!length(nms)) { message("No numbers registered."); return(invisible(NULL)) }
  lines <- c(
    "% =====================================================================",
    "%  numbers.tex --- generated by the diagFDR paper scripts. DO NOT EDIT.",
        paste0("%  Generated: ", format(Sys.time(), "%Y-%m-%d %H:%M:%S")),
    "%",
    "% =====================================================================",
    "")
  for (n in nms) {
    o <- get(n, envir = .NUMBERS)
    v <- fmt_num(o$value, o$fmt)
    if (nzchar(o$note)) lines <- c(lines, paste0("% ", n, ": ", o$note))
    lines <- c(lines, sprintf("\\newcommand{\\%s}{%s}", n, v))
  }
  writeLines(lines, path)
  message("Wrote ", length(nms), " numbers -> ", path)
  invisible(path)
}

## Print the registry as a human-readable audit table.
numbers_table <- function() {
  nms <- sort(ls(envir = .NUMBERS))
  do.call(rbind, lapply(nms, function(n) {
    o <- get(n, envir = .NUMBERS)
    data.frame(macro = n, value = fmt_num(o$value, o$fmt), note = o$note,
               stringsAsFactors = FALSE)
  }))
}

## Persist / restore the registry so scripts can be run independently.
save_numbers <- function(path = file.path(OUT, "numbers.rds")) {
  saveRDS(as.list(.NUMBERS), path); invisible(path)
}
load_numbers <- function(path = file.path(OUT, "numbers.rds")) {
  if (!file.exists(path)) return(invisible(FALSE))
  l <- readRDS(path)
  for (n in names(l)) assign(n, l[[n]], envir = .NUMBERS)
  invisible(TRUE)
}

