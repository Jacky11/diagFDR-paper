## =====================================================================
##  08 --- Supplementary Note S5: sensitivity to the two defaults
##
##  Neither rho = 0.20 (local window width) nor n_min = 200 (minimum bin
##  occupancy for the IPE) is theoretically motivated, so both are
##  recomputed over a grid (Table S6).
##
##  Output: tables/S5_rho_grid.csv, S5_ipe_grid.csv, S5_tables.tex
## =====================================================================

source("00_config.R")
load_numbers()
U <- readRDS(file.path(OUT, "universes.rds"))

RHO_GRID  <- c(0.05, 0.10, 0.20, 0.50)
NMIN_GRID <- c(50, 100, 200, 500)
NBIN_GRID <- c(5, 10, 20)

UNIV <- list("basic global" = U$basic$global,
             "basic run x precursor" = U$basic$runxprec,
             "semi global" = U$semi$global)

flag_dwin <- function(n) if (n < 5) "very sparse" else if (n < 20) "sparse" else "supported"
flag_ipe  <- function(x) if (is.na(x)) "not evaluable" else
  if (x > 0.10) "serious" else if (x > 0.05) "caution" else "ok"

## --- rho grid ---------------------------------------------------------
message("\n--- local window width rho ---")
rho_tab <- do.call(rbind, lapply(names(UNIV), function(n)
  do.call(rbind, lapply(RHO_GRID, function(r) {
    w <- local_tail_of(UNIV[[n]], ALPHA_MAIN, r, truncation = "drop")
    data.frame(universe = n, rho = r, D_win = w$D_win,
               flag = if (is.na(w$D_win)) "above export ceiling" else flag_dwin(w$D_win))
  }))))
print(rho_tab); write_tab(rho_tab, "S5_rho_grid")

stable_rho <- all(tapply(rho_tab$flag, rho_tab$universe,
                         function(z) length(unique(z)) == 1))
message(if (stable_rho) "  flags STABLE across rho"
        else "  !! flags CHANGE across rho -- replace the fixed width with a data-driven rule")

## --- n_min x n_bin grid ----------------------------------------------
message("\n--- IPE bin parameters ---")
ipe_tab <- do.call(rbind, lapply(names(UNIV), function(n) {
  t <- UNIV[[n]]
  if (!"pep" %in% names(t) || all(is.na(t$pep))) return(NULL)
  do.call(rbind, lapply(NBIN_GRID, function(nb)
    do.call(rbind, lapply(NMIN_GRID, function(nm) {
      bw <- PEP_MAX / nb
      r <- pep_reliability_of(t, "tdc", n_min = nm, pep_max = PEP_MAX, binwidth = bw)
      data.frame(universe = n, n_bins = nb, n_min = nm, IPE = r$IPE,
                 bins_used = sum(r$bins$used, na.rm = TRUE), flag = flag_ipe(r$IPE))
    }))))
}))
if (!is.null(ipe_tab)) {
  print(ipe_tab); write_tab(ipe_tab, "S5_ipe_grid")
  stable_ipe <- all(tapply(ipe_tab$flag, ipe_tab$universe,
                           function(z) length(unique(z)) == 1))
  message(if (stable_ipe) "  flags STABLE across bin parameters"
          else "  !! flags CHANGE across bin parameters -- report this honestly")
  reg("ipeRangeLow",  min(ipe_tab$IPE[ipe_tab$universe == "basic global"], na.rm = TRUE), "d4",
      "Note S5: IPE range across the grid")
  reg("ipeRangeHigh", max(ipe_tab$IPE[ipe_tab$universe == "basic global"], na.rm = TRUE), "d4",
      "Note S5")
} else {
  message("  no PEP column -- IPE grid skipped. Say so in Note S5.")
  stable_ipe <- NA
}

## --- paste-ready LaTeX ------------------------------------------------
lat <- c("% Supplementary Note S5 --- generated by 08_defaults_sensitivity.R",
  "\\begin{table}[htbp]\\centering",
  "\\caption{Sensitivity of the local window width $\\rho$. \\textbf{[ONE SENTENCE:",
  "are the flags stable?]}}", "\\label{tab:rho_sens}\\small",
  "\\begin{tabular}{lrrl}\\toprule",
  "universe & $\\rho$ & $D_{\\alpha,\\mathrm{win}}$ & flag \\\\ \\midrule",
  sprintf("%s & %.2f & %d & %s \\\\", rho_tab$universe, rho_tab$rho,
          rho_tab$D_win, rho_tab$flag),
  "\\bottomrule\\end{tabular}\\end{table}")
if (!is.null(ipe_tab)) lat <- c(lat, "",
  "\\begin{table}[htbp]\\centering",
  "\\caption{IPE across bin count and minimum bin occupancy.}",
  "\\label{tab:ipe_sens}\\small",
  "\\begin{tabular}{lrrrrl}\\toprule",
  "universe & bins & $n_{\\min}$ & IPE & bins used & flag \\\\ \\midrule",
  sprintf("%s & %d & %d & %.4f & %d & %s \\\\", ipe_tab$universe, ipe_tab$n_bins,
          ipe_tab$n_min, ipe_tab$IPE, ipe_tab$bins_used, ipe_tab$flag),
  "\\bottomrule\\end{tabular}\\end{table}")
writeLines(lat, file.path(TABDIR, "S5_tables.tex"))
message("  -> ", file.path(TABDIR, "S5_tables.tex"))

save_numbers()
message("\nDone.")
